const translations: Record<AppLanguage, Record<TranslationKey, string>> = { zh, en };

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function AppLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>('zh');

  useEffect(() => {
    AsyncStorage.getItem(LANGUAGE_KEY)
      .then((value) => {
        if (value === 'zh' || value === 'en') setLanguageState(value);
      })
      .catch((error) => console.warn('Language storage unavailable, using Chinese.', error));
  }, []);

  const setLanguage = async (nextLanguage: AppLanguage) => {
    setLanguageState(nextLanguage);
    try {
      await AsyncStorage.setItem(LANGUAGE_KEY, nextLanguage);
    } catch (error) {
      console.warn('Language storage unavailable, language kept in memory only.', error);
    }
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key: TranslationKey) => translations[language][key] ?? zh[key] ?? key,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useAppLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useAppLanguage must be used within AppLanguageProvider');
  return context;
}
